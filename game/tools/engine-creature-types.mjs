/* THE CREATURE TYPES THE ENGINE CAN READ (batch 74): what Changeling ("this object is every creature type", CR 702.73a)
 * is every one of, so "an Elf" finds a changeling and "a Forest" or "an Equipment" does not. And the planeswalker types
 * (CR 205.3j; Train C, w2b-amounts), the same way: what "the number of planeswalker types among planeswalkers you control"
 * (Tam, the Possibility) counts -- The Aetherspark's Equipment is an artifact type, not one.
 *
 * Read from the committed oracle data (data/engine/oracle.json), never typed by hand and never from the Comprehensive
 * Rules' text: every subtype on a Creature or Kindred type line, less any that also appears on a type line that is
 * neither -- so Dryad Arbor's Forest, a Food creature's Food and an Equipment creature's Equipment are not creature
 * types, as they are not. A subtype is a word, as card identities split them (cardlib.py, cards/compile.mjs).
 *
 *   node game/tools/engine-creature-types.mjs           report
 *   node game/tools/engine-creature-types.mjs --write   write game/engine/keywords/creature-types.mjs and planeswalker-types.mjs
 *   node game/tools/engine-creature-types.mjs --check   exit 1 if either file is not what the oracle data says
 */

import {readFileSync, writeFileSync} from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, "..", "..");
const OUT = path.join(REPO, "game", "engine", "keywords", "creature-types.mjs");
const PLANESWALKER_OUT = path.join(REPO, "game", "engine", "keywords", "planeswalker-types.mjs");

/* A creature token a card makes, as its text describes it: "create a 0/0 black Zombie Army creature token" (amass). Its
   subtypes are the capitalized words between its colors and "creature token". */
const TOKEN = /(?:\d+|X)\/(?:\d+|X) (?:(?:white|blue|black|red|green|colorless|multicolored|and)[ ,]+)*((?:[A-Z][A-Za-z'-]+ )+)(?:(?:legendary|snow|artifact|enchantment) )*creature tokens?/g;

/** Every creature type the oracle data shows, sorted. */
export function creatureTypesFrom(oracle) {
  const creature = new Set(), other = new Set();
  for (const card of oracle.cards ?? []) {
    const lines = Array.isArray(card.faces) && card.faces.length ? card.faces.map((f) => f.type).filter(Boolean) : [card.type ?? ""];
    for (const line of lines) {
      const [left, right = ""] = line.split(" — ");
      const words = left.split(/\s+/), subtypes = right.split(/\s+/).filter(Boolean);
      const into = words.includes("Creature") || words.includes("Kindred") || words.includes("Tribal") ? creature : other;
      for (const subtype of subtypes) into.add(subtype);
    }
    /* And a creature token's: Army, Servo, Germ and their kin are creature types no card's type line carries, and a
       changeling is each of them ("if you don't control an Army creature"). An enchantment creature token's Shrine is an
       enchantment type, and the type lines that carry it leave it out below. */
    const texts = Array.isArray(card.faces) && card.faces.length ? card.faces.map((f) => f.text ?? "") : [card.text ?? ""];
    for (const text of texts) for (const [, named] of text.matchAll(TOKEN)) for (const subtype of named.trim().split(/\s+/)) creature.add(subtype);
  }
  return [...creature].filter((t) => !other.has(t)).sort();
}

/** Every planeswalker type the oracle data shows, sorted (CR 205.3j): each subtype on a Planeswalker type line, less any that
    also appears on a type line without Planeswalker -- an artifact planeswalker's Equipment is an artifact type. */
export function planeswalkerTypesFrom(oracle) {
  const walker = new Set(), other = new Set();
  for (const card of oracle.cards ?? []) {
    const lines = Array.isArray(card.faces) && card.faces.length ? card.faces.map((f) => f.type).filter(Boolean) : [card.type ?? ""];
    for (const line of lines) {
      const [left, right = ""] = line.split(" — ");
      const into = left.split(/\s+/).includes("Planeswalker") ? walker : other;
      for (const subtype of right.split(/\s+/).filter(Boolean)) into.add(subtype);
    }
  }
  return [...walker].filter((t) => !other.has(t)).sort();
}

export function planeswalkerModuleText(types) {
  return `/* Copyright (c) 2026 Rob Minor. All rights reserved. See LICENSE. */

/* GENERATED by \`node game/tools/engine-creature-types.mjs --write\` from data/engine/oracle.json: every planeswalker type on a
 * Commander-legal card (CR 205.3j), what "the number of planeswalker types among" counts (keywords/types.mjs). Do not edit
 * by hand. */

export const PLANESWALKER_TYPES = Object.freeze(${JSON.stringify(types)});
`;
}

export function moduleText(types) {
  return `/* Copyright (c) 2026 Rob Minor. All rights reserved. See LICENSE. */

/* GENERATED by \`node game/tools/engine-creature-types.mjs --write\` from data/engine/oracle.json: every creature type on a
 * Commander-legal card, what Changeling is every one of (keywords/types.mjs). Do not edit by hand. */

export const CREATURE_TYPES = Object.freeze(${JSON.stringify(types)});
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const oracle = JSON.parse(readFileSync(path.join(REPO, "data", "engine", "oracle.json"), "utf8"));
  const types = creatureTypesFrom(oracle), walkers = planeswalkerTypesFrom(oracle);
  const files = [[OUT, moduleText(types), `${types.length} creature types`], [PLANESWALKER_OUT, planeswalkerModuleText(walkers), `${walkers.length} planeswalker types`]];
  if (process.argv.includes("--write")) for (const [out, text, said] of files) { writeFileSync(out, text); console.log(`Wrote ${path.relative(REPO, out)}: ${said}`); }
  else if (process.argv.includes("--check")) {
    for (const [out, text, said] of files) {
      let current = "";
      try { current = readFileSync(out, "utf8"); } catch { /* missing is drift */ }
      if (current !== text) { console.error(`${path.relative(REPO, out)} is not what the oracle data says; run --write`); process.exit(1); }
      console.log(`${path.relative(REPO, out)} matches the oracle data: ${said}`);
    }
  } else for (const [, , said] of files) console.log(said);
}
