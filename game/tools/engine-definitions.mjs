/* THE TABLE'S DEFINITIONS, AS ONE MODULE (the plan review's A2 and C4: M5, the definitions served to the table).
 *
 * The cloud table runs in a Worker, which reads no file system: the card directory (`game/engine/cards/<letter>/`)
 * reaches it as `game/engine/cards/definitions.mjs`, every playable definition compiled and keyed by its folded name,
 * which `tools/release-pages.mjs` bundles with the rest of the engine (`workerModules`). Generated from the directory,
 * never edited: `--write` writes it, `--check` says whether it is the directory as it stands (tests/engine-cards.mjs
 * holds it to that). The scenarios stay out: the table plays cards, it does not test them.
 *
 *   node game/tools/engine-definitions.mjs --write
 *   node game/tools/engine-definitions.mjs --check
 */

import {readFileSync, writeFileSync} from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";
import {loadCardScripts, CARDS_DIR} from "./engine-cards.mjs";
import {createCardIndex, foldName} from "../engine/cards/index.mjs";

export const DEFINITIONS_MODULE = path.join(CARDS_DIR, "definitions.mjs");

/* The directory as committed: the hand-authored definitions. The card loader's compiled ones (data/engine/scripts) are a
   working folder on the machine that runs it, not part of the repository, so they join only once they are committed --
   the module is then the same on every machine that checks out the same commit. */
const committed = () => createCardIndex(loadCardScripts().map((entry) => ({...entry, source: "hand"})));

/** The module's text: every playable definition, one to a line, in name order. */
export function definitionsModule(index = committed()) {
  const lines = index.names
    .filter((name) => index.resolve(name)?.playable === true)
    .map((name) => {
      const {status} = index.resolve(name);
      return `  ${JSON.stringify(foldName(name))}: ${JSON.stringify({name, status, definition: index.definition(name)})},`;
    });
  return `/* Copyright (c) 2026 Rob Minor. All rights reserved. See LICENSE. */

/* GENERATED by game/tools/engine-definitions.mjs from the card directory -- do not edit; run it with --write.
 *
 * Every playable definition (${lines.length}), keyed by the card's folded name: what the cloud table plays (cloud/game-room.mjs).
 * A Worker reads no file system, so the directory reaches it as this module. */

/* The fold game/engine/cards/index.mjs matches names by: case, accents, punctuation and spacing make no other card. */
const fold = (name) => String(name ?? "").normalize("NFKD").replace(/[\\u0300-\\u036f]/g, "").toLowerCase()
  .replace(/[^a-z0-9/ ]+/g, "").replace(/\\s+/g, " ").trim();

export const DEFINITIONS = Object.freeze({
${lines.join("\n")}
});

/** A card's definition for \`addObject\`, fresh each call -- or null when the table cannot play it. */
export function tableDefinition(name) {
  const hit = DEFINITIONS[fold(name)];
  return hit ? structuredClone(hit.definition) : null;
}
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const want = definitionsModule();
  if (process.argv.includes("--write")) {
    writeFileSync(DEFINITIONS_MODULE, want);
    console.log(`engine-definitions: wrote ${path.relative(process.cwd(), DEFINITIONS_MODULE)} (${(want.length / 1e6).toFixed(2)} MB)`);
  } else {
    let have = "";
    try { have = readFileSync(DEFINITIONS_MODULE, "utf8"); } catch { /* missing is stale */ }
    if (have !== want) { console.error("engine-definitions: definitions.mjs is not the card directory as it stands -- run with --write"); process.exit(1); }
    console.log("engine-definitions: definitions.mjs is current");
  }
}
