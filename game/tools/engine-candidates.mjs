/* THE CANDIDATES, AS ONE MODULE FOR THE TABLE (card load step 5; Linear ROB-91; docs/engine/plan-card-load-program.md).
 *
 * Rob's decision 2: a candidate seats at playtest tables only, labeled. The table runs in a Worker, which reads no file
 * system, so the candidates (`data/engine/candidates.json`, the card compiler's) reach it as
 * `game/engine/cards/candidates.mjs`: each one put back together with its oracle record and compiled, keyed by its
 * folded name -- and with them the backstop's (data/engine/scripts, written by game/tools/engine-compile.mjs and stored
 * `provisional`), which no review has confirmed either and which no table seated before (card load step 5), which `tools/release-pages.mjs` bundles with the rest of the engine. Each definition is kept as JSON
 * text and parsed only when a playtest table asks for the card, so the Worker does not parse two thousand definitions
 * every time it starts. Generated, never edited: `--write` writes it, `--check` says whether it is the candidates file
 * as it stands (tests/table-candidates.mjs holds it to that).
 *
 *   node game/tools/engine-candidates.mjs --write
 *   node game/tools/engine-candidates.mjs --check
 */

import {readFileSync, writeFileSync} from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";
import {CARDS_DIR, loadCardScripts, loadCompiledScripts} from "./engine-cards.mjs";
import {compileScript, foldName, createCardIndex} from "../engine/cards/index.mjs";
import {CANDIDATES_FILE, scriptOf} from "./card-compiler.mjs";

export const CANDIDATES_MODULE = path.join(CARDS_DIR, "candidates.mjs");
const ORACLE_FILE = path.join(path.dirname(CANDIDATES_FILE), "oracle.json");
const read = (file) => JSON.parse(readFileSync(file, "utf8"));

/** The backstop's cards the directory does not define, still `provisional`: the scripts, as committed. */
export function backstopScripts(compiled = loadCompiledScripts(), hand = createCardIndex(loadCardScripts().map((e) => ({...e, source: "hand"})))) {
  return compiled.filter((e) => e.status === "provisional" && e.script?.identity?.name && !hand.resolve(e.script.identity.name)).map((e) => e.script);
}

/** The module's text: every candidate that compiles, one to a line, in name order: the compiler's, then the backstop's. */
export function candidatesModule(file = read(CANDIDATES_FILE), oracle = read(ORACLE_FILE), backstop = backstopScripts()) {
  const byName = new Map(oracle.cards.map((c) => [c.name, c]));
  const lines = [], taken = new Set();
  const add = (name, script) => {
    const {definition, problems} = compileScript(script);
    if (problems.length || !definition || taken.has(foldName(name))) return false;
    taken.add(foldName(name));
    lines.push(`  ${JSON.stringify(foldName(name))}: ${JSON.stringify(JSON.stringify(definition))},`);
    return true;
  };
  for (const c of file.cards) if (byName.has(c.name)) add(c.name, scriptOf(c, byName.get(c.name)));
  const compiled = lines.length;
  const fromBackstop = [...backstop].sort((a, b) => (a.identity.name < b.identity.name ? -1 : 1)).filter((script) => add(script.identity.name, script)).length;
  return `/* Copyright (c) 2026 Rob Minor. All rights reserved. See LICENSE. */

/* GENERATED by game/tools/engine-candidates.mjs from data/engine/candidates.json -- do not edit; run it with --write.
 *
 * Every candidate (${lines.length}: ${compiled} from the card compiler, ${fromBackstop} from the backstop), keyed by the card's folded name, its definition as JSON text: what a
 * playtest table plays beside the card directory, labeled (cloud/game-room.mjs; game/room/room.mjs, \`candidates\`).
 * No other table seats one (Rob's decision 2). */

/* The fold game/engine/cards/index.mjs matches names by: case, accents, punctuation and spacing make no other card. */
const fold = (name) => String(name ?? "").normalize("NFKD").replace(/[\\u0300-\\u036f]/g, "").toLowerCase()
  .replace(/[^a-z0-9/ ]+/g, "").replace(/\\s+/g, " ").trim();

export const CANDIDATE_SOURCE = ${JSON.stringify({oracle: file.oracle ?? null, cards: lines.length, compiler: compiled, backstop: fromBackstop})};

const CANDIDATES = Object.freeze({
${lines.join("\n")}
});

/** A candidate's definition for \`addObject\`, fresh each call -- or null when the card is no candidate. */
export function candidateDefinition(name) {
  const hit = CANDIDATES[fold(name)];
  return hit ? JSON.parse(hit) : null;
}
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const want = candidatesModule();
  if (process.argv.includes("--write")) {
    writeFileSync(CANDIDATES_MODULE, want);
    console.log(`engine-candidates: wrote ${path.relative(process.cwd(), CANDIDATES_MODULE)} (${(want.length / 1e6).toFixed(2)} MB)`);
  } else {
    let have = "";
    try { have = readFileSync(CANDIDATES_MODULE, "utf8"); } catch { /* missing is stale */ }
    if (have !== want) { console.error("engine-candidates: candidates.mjs is not the candidates file as it stands -- run with --write"); process.exit(1); }
    console.log("engine-candidates: candidates.mjs is current");
  }
}
