/* Copyright (c) 2026 Rob Minor. All rights reserved. See LICENSE.
 *
 * Writes game/engine/pilots/veteran-skill.mjs from game/engine/pilots/veteran-skill.md, the Veteran agent's instruction set
 * (docs/ai-players/PLAN-2026-10-26.html §6). The Markdown is the source, written to be read; a Worker reads no file system, so the
 * system prompt the model gets is this module, and tests/veteran-agent.mjs holds the two equal.
 *
 *   node tools/build-veteran-skill.mjs          write the module
 *   node tools/build-veteran-skill.mjs --check  exit 1 if the module is not what the Markdown says
 */
import {readFileSync, writeFileSync} from "node:fs";

const SRC = new URL("../game/engine/pilots/veteran-skill.md", import.meta.url), OUT = new URL("../game/engine/pilots/veteran-skill.mjs", import.meta.url);
export const moduleText = (md = readFileSync(SRC, "utf8")) => `/* Copyright (c) 2026 Rob Minor. All rights reserved. See LICENSE. */

/* GENERATED by tools/build-veteran-skill.mjs from veteran-skill.md -- do not edit; edit the Markdown and run the tool. The Veteran
 * agent's instruction set, as the system prompt cloud/ai.mjs hands the model (a Worker reads no file system). */
export const VETERAN_SKILL = ${JSON.stringify(md.trim())};
`;

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = moduleText();
  if (process.argv.includes("--check")) {
    let now = "";
    try {now = readFileSync(OUT, "utf8");} catch {}
    if (now !== text) {console.error("veteran-skill.mjs is not what veteran-skill.md says: run node tools/build-veteran-skill.mjs"); process.exit(1);}
    console.log("veteran-skill.mjs matches veteran-skill.md");
  } else {writeFileSync(OUT, text); console.log(`wrote game/engine/pilots/veteran-skill.mjs (${(text.length / 1024).toFixed(1)} KB)`);}
}
