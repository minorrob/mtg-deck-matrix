/* THE DECK ADVISOR'S CARD FACTS, FOR THE WORKER (AI-4, docs/plan-to-done-2026-09-30.md).
 *
 * The advisor's brief (advise-brief.js) is built by the Worker from the person's own library (cloud/advise.mjs), and
 * the brief needs a few facts of each card the library holds that its backup does not carry: its type line, color
 * identity and mana value, its roles (the role lens's), its market price, its EDHREC rank, and whether it is a game
 * changer. They come from the app's own catalog, data/cards.json (4.8 MB, too much for a Worker), slimmed to those
 * facts in cloud/advise-cards.mjs, keyed by the catalog's own fold of a name (card-catalog.js `folded`).
 *
 *   node tools/build-advise-cards.mjs --write    rewrite cloud/advise-cards.mjs
 *   node tools/build-advise-cards.mjs --check    exit 1 if it is not what data/cards.json makes (tests/generators.mjs)
 */
import {readFileSync, writeFileSync} from "node:fs";
import {createRequire} from "node:module";
import path from "node:path";
import {fileURLToPath} from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "cloud", "advise-cards.mjs");
const Catalog = createRequire(import.meta.url)(path.join(ROOT, "card-catalog.js"));

/* The catalog's fold of a name (card-catalog.js `folded`), written into the module the Worker reads, which cannot import
   card-catalog.js; every record's key is checked against the catalog's own as the module is made. */
const fold = (s) => String(s || "").normalize("NFKC").trim().toLowerCase();

/** The module's text, from the catalog's records. */
export function adviseCardsModule(records) {
  const rows = {};
  for (const c of [...records].sort((a, b) => a.name.localeCompare(b.name))) {
    const key = fold(c.name);
    if (key !== Catalog.folded(c.name)) throw new Error(`build-advise-cards: the fold written for the Worker differs from the catalog's for ${c.name}`);
    if (!key || rows[key]) continue;
    rows[key] = [c.oracleId || null, c.typeLine || "", (c.colorIdentity || []).join(""), Number.isFinite(c.manaValue) ? c.manaValue : null,
      [...(c.roles || [])].sort(), Number.isFinite(c.price) ? Math.round(c.price * 100) / 100 : null, Number.isFinite(c.rank) ? c.rank : null, c.gameChanger ? 1 : 0];
  }
  const body = Object.entries(rows).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
  return `/* Copyright (c) 2026 Rob Minor. All rights reserved. See LICENSE. */

/* GENERATED by tools/build-advise-cards.mjs from data/cards.json -- do not edit; run it with --write.
 *
 * The deck advisor's card facts (${Object.keys(rows).length} cards), keyed by the catalog's fold of a name: [oracle id, type line,
 * color identity, mana value, roles, market price, EDHREC rank, game changer]. The Worker reads no file system, so the
 * catalog reaches it as this module (cloud/advise.mjs). */
export const ADVISE_FIELDS = Object.freeze(["oracleId", "typeLine", "colorIdentity", "manaValue", "roles", "price", "rank", "gameChanger"]);
/* The catalog's fold of a name (card-catalog.js \`folded\`), which the keys are. */
export const fold = ${fold.toString()};
export const ADVISE_CARDS = Object.freeze({
${body}
});
`;
}

const records = JSON.parse(readFileSync(path.join(ROOT, "data", "cards.json"), "utf8")).cards;
const text = adviseCardsModule(records);
const args = process.argv.slice(2);
if (args.includes("--write")) {
  writeFileSync(OUT, text);
  console.log(`build-advise-cards: wrote cloud/advise-cards.mjs (${(text.length / 1024).toFixed(0)} KB)`);
} else if (args.includes("--check")) {
  let current = "";
  try {current = readFileSync(OUT, "utf8");} catch {}
  if (current !== text) {console.error("build-advise-cards: cloud/advise-cards.mjs is not what data/cards.json makes; run node tools/build-advise-cards.mjs --write"); process.exit(1);}
  console.log("build-advise-cards: cloud/advise-cards.mjs matches data/cards.json");
} else {
  console.error("Usage: node tools/build-advise-cards.mjs --write | --check");
  process.exit(2);
}
